/**
 * Единственный редактируемый файл с проектами.
 *
 * В ленте — ровно четыре карточки. Это авторские визуальные концепты сайтов,
 * а не выполненные клиентские заказы: у каждой карточки стоит бейдж «Концепт»,
 * выдуманных отзывов, показателей и действующих доменов здесь нет.
 *
 * Как добавить свою работу:
 *  1. Скопируйте любую карточку ниже и измените поля.
 *  2. Выберите `concept` — от него зависит, какой превью-концепт рисуется.
 *  3. Оставьте `demo: true`, пока это не реальный выполненный проект.
 */

/** Какой превью-концепт сайта рисуется внутри карточки. */
export type Concept = 'bakery' | 'ceramics' | 'accounting' | 'sailing'

export interface Project {
  /** Уникальный идентификатор карточки. */
  id: string
  /** Метка в верхней строке карточки — ниша проекта. */
  label: string
  /** Название проекта. */
  title: string
  /** Подпись в строке «браузера» над превью. Не домен — живых сайтов нет. */
  frameNote: string
  /** Короткое описание под превью. */
  description: string
  /** Тип работы, например «Лендинг / веб-разработка». */
  meta: string
  /** Превью-концепт, который рисуется в карточке. */
  concept: Concept
  /** true — карточка помечается бейджем «Концепт». */
  demo: boolean
}

