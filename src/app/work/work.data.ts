/**
 * Кейсы Waystroke: контракт данных и хранилище.
 *
 * Публичных клиентских проектов у студии пока нет, а придумывать их нельзя:
 * выдуманные клиенты, отзывы и цифры результата вредят и доверию, и
 * репутации поиска. Поэтому здесь лежит только формат записи и пустой
 * список — секция «Кейсы» показывает честный пустой состояние.
 *
 * Как добавить реальный кейс:
 * 1. положить обложку в `public/images/cases/<имя>.webp` (960 и 480 px,
 *    как у концептов, с `alt` из описания ниже);
 * 2. дописать объект в `PROJECTS` — поля ниже описывают, что именно нужно;
 * 3. секция отрисуется сама, отдельная вёрстка не требуется.
 *
 * `image` и `thumb` — относительные пути от корня сайта: с `<base href="/">`
 * они попадают в сборку как есть.
 */
export interface CaseStudy {
  /** Короткое имя проекта в интерфейсе: «Сайт для кофейни». */
  title: string;
  /** Задача одной строкой: что клиент хотел изменить. */
  task: string;
  /** Что сделано: объём работ, без похвалы в свою сторону. */
  scope: string;
  /** Формат и срок — те же ориентиры, что и в карточках услуг. */
  format: string;
  /** Адрес опубликованного сайта, если клиент разрешил ссылку. */
  url?: string;
  /** Обложка для карточки. */
  image: string;
  /** Уменьшенная обложка для `srcset` — 480 px. */
  thumb: string;
  /** `alt` изображения: что изображено, без слов «изображение» и «фото». */
  alt: string;
}

export const PROJECTS: readonly CaseStudy[] = [];
